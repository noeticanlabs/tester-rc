// CohBit-Copilot v14.4 — Repair Review UX
// Read-only review operations on the T8 repair queue.
// Enables human review of AST-guided proposals without granting mutation authority.
//
// Operating law:
//   Review may inspect, list, explain, approve, or reject repair tasks.
//   Approve marks the repair as reviewed — it does NOT apply the patch.
//   Reject records the decision — it does NOT delete the finding.
//   All operations are read/review-side only unless explicit gate authorization exists.

import {
    REPAIR_QUEUE,
    completeRepair,
    type RepairTask,
    type RepairPriority,
} from '../packages/tooling/src/T8_repair_queue.js';

// ─── Types ─────────────────────────────────────────────────────

export interface RepairListOptions {
    status?: 'open' | 'in_progress' | 'completed' | 'rejected' | 'all';
    priority?: RepairPriority;
    limit?: number;
}

export interface RepairDetail {
    task: RepairTask;
    index: number;
}

// ─── List Repairs ──────────────────────────────────────────────

export function listRepairs(options: RepairListOptions = {}): RepairTask[] {
    let tasks = [...REPAIR_QUEUE];

    if (options.status && options.status !== 'all') {
        tasks = tasks.filter(t => t.status === options.status);
    }

    if (options.priority) {
        tasks = tasks.filter(t => t.priority === options.priority);
    }

    // Most recent first
    tasks.sort((a, b) => b.createdAt.localeCompare(a.createdAt));

    if (options.limit && options.limit > 0) {
        tasks = tasks.slice(0, options.limit);
    }

    return tasks;
}

export function formatRepairList(tasks: RepairTask[]): string {
    if (tasks.length === 0) return '(no repair tasks)';

    const lines: string[] = [];
    const headers = ['Repair ID', 'Status', 'Priority', 'Problem', 'Proposal ID'];
    const rows = tasks.map(t => [
        t.repairTaskId,
        statusIcon(t.status) + ' ' + t.status,
        t.priority,
        t.problem.length > 50 ? t.problem.slice(0, 47) + '...' : t.problem,
        t.proposalId ?? '-',
    ]);

    // Simple aligned format
    const widths = [14, 14, 8, 52, 24];
    lines.push(headers.map((h, i) => h.padEnd(widths[i]!)).join(' '));
    lines.push(headers.map((_, i) => '-'.repeat(widths[i]!)).join(' '));

    for (const row of rows) {
        lines.push(row.map((r, i) => r.padEnd(widths[i]!)).join(' '));
    }

    lines.push(`\n${tasks.length} repair task(s)`);
    return lines.join('\n');
}

function statusIcon(status: string): string {
    switch (status) {
        case 'open': return '⬜';
        case 'in_progress': return '🔄';
        case 'completed': return '✅';
        case 'rejected': return '❌';
        default: return '❓';
    }
}

// ─── Show Repair ───────────────────────────────────────────────

export function showRepair(proposalIdOrRepairId: string): RepairDetail | null {
    const idx = REPAIR_QUEUE.findIndex(
        t => t.repairTaskId === proposalIdOrRepairId || t.proposalId === proposalIdOrRepairId
    );
    if (idx === -1) return null;
    return { task: REPAIR_QUEUE[idx]!, index: idx };
}

export function formatRepairDetail(detail: RepairDetail): string {
    const t = detail.task;
    const lines = [
        `Repair ID:   ${t.repairTaskId}`,
        `Status:      ${statusIcon(t.status)} ${t.status}`,
        `Priority:    ${t.priority}`,
        `Type:        ${t.repairType}`,
        `Problem:     ${t.problem}`,
        `Action:      ${t.requiredAction}`,
        `Source:      ${t.sourceRecordId}`,
        `Finding ID:  ${t.findingId ?? '-'}`,
        `Proposal ID: ${t.proposalId ?? '-'}`,
        `Created:     ${t.createdAt}`,
    ];
    return lines.join('\n');
}

// ─── Explain Repair ────────────────────────────────────────────

export function explainRepair(proposalIdOrRepairId: string): string | null {
    const detail = showRepair(proposalIdOrRepairId);
    if (!detail) return null;

    const t = detail.task;
    const lines = [
        formatRepairDetail(detail),
        '',
        '── Strategy Reasoning ──',
        '',
        `This repair was generated by the v14.3 AST-guided proposal bridge.`,
        `The finding (${t.findingId ?? 'unknown'}) matched a riskKind that has a known safe`,
        `replacement strategy, and the AST-lite FunctionContext verified structural`,
        `preconditions (e.g., enclosing function return type, production vs. test context).`,
        '',
        `The proposal has NOT been applied. It requires human review and explicit`,
        `authorization through the gate pipeline before any source code mutation.`,
        '',
        `Behavior note: If this is an unwrap/expect → ? conversion, the API behavior`,
        `may change from panic-on-failure to error propagation. Verify caller expectations.`,
    ];
    return lines.join('\n');
}

// ─── Approve Repair ────────────────────────────────────────────

export interface ApproveRepairResult {
    success: boolean;
    repairTaskId?: string;
    reason: string;
}

export function approveRepair(proposalIdOrRepairId: string): ApproveRepairResult {
    const detail = showRepair(proposalIdOrRepairId);
    if (!detail) {
        return { success: false, reason: `No repair found for "${proposalIdOrRepairId}"` };
    }

    const t = detail.task;
    if (t.status === 'completed') {
        return { success: false, repairTaskId: t.repairTaskId, reason: 'Repair is already completed.' };
    }
    if (t.status === 'rejected') {
        return { success: false, repairTaskId: t.repairTaskId, reason: 'Repair was previously rejected. Use a new proposal if needed.' };
    }

    const ok = completeRepair(t.repairTaskId);
    if (!ok) {
        return { success: false, repairTaskId: t.repairTaskId, reason: 'Failed to mark repair as completed.' };
    }

    return {
        success: true,
        repairTaskId: t.repairTaskId,
        reason: `Repair ${t.repairTaskId} marked as reviewed (completed). Patch has NOT been applied — use the gate pipeline to apply.`,
    };
}

// ─── Reject Repair ─────────────────────────────────────────────

export interface RejectRepairResult {
    success: boolean;
    repairTaskId?: string;
    reason: string;
}

export function rejectRepair(
    proposalIdOrRepairId: string,
    rejectionReason: string,
): RejectRepairResult {
    const detail = showRepair(proposalIdOrRepairId);
    if (!detail) {
        return { success: false, reason: `No repair found for "${proposalIdOrRepairId}"` };
    }

    const t = detail.task;
    if (t.status === 'completed') {
        return { success: false, repairTaskId: t.repairTaskId, reason: 'Cannot reject a completed repair.' };
    }

    t.status = 'rejected';
    t.requiredAction = `REJECTED: ${rejectionReason}. Original action: ${t.requiredAction}`;

    return {
        success: true,
        repairTaskId: t.repairTaskId,
        reason: `Repair ${t.repairTaskId} rejected: ${rejectionReason}`,
    };
}

// ─── Summary ───────────────────────────────────────────────────

export function repairSummary(): { total: number; open: number; inProgress: number; completed: number; rejected: number } {
    const counts = { total: 0, open: 0, inProgress: 0, completed: 0, rejected: 0 };
    for (const t of REPAIR_QUEUE) {
        counts.total++;
        switch (t.status) {
            case 'open': counts.open++; break;
            case 'in_progress': counts.inProgress++; break;
            case 'completed': counts.completed++; break;
            case 'rejected': counts.rejected++; break;
        }
    }
    return counts;
}

export function formatRepairSummary(): string {
    const s = repairSummary();
    return [
        `Repairs: ${s.total} total — ${s.open} open, ${s.inProgress} in progress, ${s.completed} completed, ${s.rejected} rejected`,
    ].join('\n');
}